#include<iostream>

using namespace std;

// Demonstrates basic fundamental data types in C++
int main(){
    // Variable declarations with fundamental data types
    int roll = 2307;       // Integer data type
    char grade ='A';       // Character data type
    float fee = 20000;     // Floating-point data type

    // Output formatted values to console
    cout<<"Roll No.: "<<roll<<endl;
    cout<<"Grade : "<<grade<<endl;
    cout<<"Fee: "<<fee<<endl;
    return 0;
}
